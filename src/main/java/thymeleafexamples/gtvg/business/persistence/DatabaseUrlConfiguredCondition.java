package thymeleafexamples.gtvg.business.persistence;

import org.springframework.context.annotation.Condition;
import org.springframework.context.annotation.ConditionContext;
import org.springframework.core.type.AnnotatedTypeMetadata;
import org.springframework.util.StringUtils;

public class DatabaseUrlConfiguredCondition implements Condition {

    public boolean matches(final ConditionContext context, final AnnotatedTypeMetadata metadata) {
        return StringUtils.hasText(
                context.getEnvironment().getProperty(DatabaseDemoPersistenceConfig.DATABASE_URL_PROPERTY));
    }

}
